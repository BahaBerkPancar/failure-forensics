"""Generate a readable pytest file that replays failing inputs through a user-supplied entry point.

Safety: no text from the store is ever placed in code, comments or docstrings. Inputs and
metadata are embedded as a Python literal built by `pprint.pformat` (str/int/float/bool/None/list/
dict only, escaped by `repr`) and verified with `ast.literal_eval` before the file is written.
The entry point and checker names are validated against a strict `module:function` pattern.
"""

from __future__ import annotations

import ast
import math
import pprint
import re
from typing import Any

from .cases import ExportCase

HEADER = "# Generated by failure-forensics (ff export --to pytest)."
_SPEC = re.compile(r"[A-Za-z_][A-Za-z0-9_]*(\.[A-Za-z_][A-Za-z0-9_]*)*:[A-Za-z_][A-Za-z0-9_]*")


def valid_spec(spec: str) -> bool:
    return bool(_SPEC.fullmatch(spec))


def _clean(value: Any) -> Any:
    """Reduce to literal-safe types (JSON-like); non-finite floats and odd types become strings."""
    if isinstance(value, bool) or value is None or isinstance(value, (int, str)):
        return value
    if isinstance(value, float):
        return value if math.isfinite(value) else str(value)
    if isinstance(value, (list, tuple)):
        return [_clean(v) for v in value]
    if isinstance(value, dict):
        return {str(k): _clean(v) for k, v in value.items()}
    return str(value)


def _literal(value: Any) -> str:
    text = pprint.pformat(value, width=100, sort_dicts=False)
    if ast.literal_eval(text) != value:  # never emit something that does not round-trip
        raise ValueError("value does not round-trip as a Python literal")
    return text


def render_pytest(cases: list[ExportCase], entry: str, checker: str | None = None) -> str:
    if not valid_spec(entry) or (checker is not None and not valid_spec(checker)):
        raise ValueError("entry and checker must look like 'package.module:function'")
    rows = [
        {"id": c.id, "step": c.step, "kind": c.kind, "error_type": c.error_type, "input": _clean(c.input),
         "has_expected": c.has_expected, "expected": _clean(c.expected) if c.has_expected else None,
         "redacted": c.redacted, "truncated": c.truncated}
        for c in cases
    ]
    n_red = sum(c.redacted for c in cases)
    n_rev = sum(not c.has_expected and c.error_type is None for c in cases)
    subst = {
        "COUNT": str(len(cases)), "REDACTED": str(n_red), "REVIEW": str(n_rev),
        "ENTRY": _literal(entry), "CHECKER": _literal(checker),
        "SIGNATURE": _literal(cases[0].signature if cases else ""), "CASES": _literal(rows),
    }
    # one pass, so text inside an inserted literal is never treated as a placeholder
    body = re.sub(r"@@([A-Z]+)@@", lambda m: subst[m.group(1)], _TEMPLATE)
    ast.parse(body)  # the generated file must compile
    return body


_TEMPLATE = HEADER + '''
# One test per distinct failing input (@@COUNT@@). Inputs are the values failure-forensics had already
# redacted and truncated when it stored them; @@REDACTED@@ case(s) contain redaction markers
# and may be incomplete. @@REVIEW@@ case(s) have no known-good expectation: they are skipped
# unless you pass a checker.
import importlib

import pytest

ENTRY = @@ENTRY@@  # "module:function", called with the recorded input
CHECKER = @@CHECKER@@  # optional "module:function(input, result, case) -> bool"
SIGNATURE = @@SIGNATURE@@

CASES = @@CASES@@


def _load(spec):
    module, _, name = spec.partition(":")
    return getattr(importlib.import_module(module), name)


@pytest.mark.parametrize("case", CASES, ids=[c["id"] for c in CASES])
def test_no_longer_fails_the_same_way(case):
    try:
        result = _load(ENTRY)(case["input"])
    except Exception as exc:
        if case["error_type"] in {c.__name__ for c in type(exc).__mro__}:
            pytest.fail(
                "still fails the same way: %s (recorded at step %s; %s)" % (case["error_type"], case["step"], SIGNATURE),
                pytrace=False,
            )
        raise  # a different exception is a different problem, but not a pass
    if CHECKER:
        assert _load(CHECKER)(case["input"], result, case), "checker rejected the result"
    elif case["error_type"]:
        pass  # the recorded failure was an exception, and it did not happen
    elif case["has_expected"]:
        assert result == case["expected"]
    elif case["kind"] == "empty_output":
        assert result not in (None, "", [], {})
    else:
        pytest.skip("needs review: no passing run to take an expected value from; pass --checker")
'''
